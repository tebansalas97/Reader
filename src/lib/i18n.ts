const dictionaries: Record<'es' | 'en', Dict> = { es, en };

let current: 'es' | 'en' = 'es';

export function setLanguage(lang: 'es' | 'en'): void {
  current = lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = dictionaries[current][key] ?? es[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
}
